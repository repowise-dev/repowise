"""Removing a TOML table without taking the user's comments with it.

Every test here is a regression. The first implementation of ``remove_table``
shared ``replace_table``'s regex, whose terminating lookahead is ``(?=^\\s*\\[|\\Z)``
and whose ``\\s`` does not match ``#``. So a comment line never ended the span,
everything from our header to the next live header was consumed, and a
``.codex/config.toml`` whose remainder was the user's commented-out server came
back empty. The caller read empty as "this file was ours" and deleted it, then
removed ``.codex/`` behind it, and reported a clean ``removed``. The directory is
gitignored in most repos, so nothing showed it.

That is two of this track's named historical bugs at once: deleting a section
that still held a commented-out server, and treating an empty parse as an empty
file. It is worse than the second, because the regex had already eaten the
evidence before the emptiness test ran.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from repowise.cli.agent_targets.formats.toml_merge import (
    remove_key_line,
    remove_table,
    table_is_bare,
)
from repowise.cli.agent_targets.targets.codex import (
    project_config_path,
    remove_server_config,
)
from repowise.cli.agent_targets.types import FileAction


def _write(repo: Path, text: str) -> Path:
    path = project_config_path(repo)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# remove_table
# ---------------------------------------------------------------------------


def test_a_commented_out_server_after_our_table_survives() -> None:
    text = (
        '[mcp_servers.repowise]\ncommand = "repowise"\n\n'
        '# [mcp_servers.other]\n# command = "other-server"\n'
    )
    remaining = remove_table(text, "mcp_servers.repowise")

    assert "mcp_servers.other" in remaining
    assert "other-server" in remaining
    assert "repowise" not in remaining


def test_the_users_prose_comments_after_our_table_survive() -> None:
    text = (
        '[mcp_servers.repowise]\ncommand = "repowise"\n\n'
        "# my notes about codex\n# remember sandbox mode\n"
    )
    remaining = remove_table(text, "mcp_servers.repowise")

    assert "my notes about codex" in remaining
    assert "remember sandbox mode" in remaining


def test_a_warning_comment_before_a_live_sibling_survives() -> None:
    text = (
        '[mcp_servers.repowise]\ncommand = "repowise"\n\n'
        "# this one talks to prod, do not remove\n"
        '[mcp_servers.prod]\ncommand = "p"\n'
    )
    remaining = remove_table(text, "mcp_servers.repowise")

    assert "do not remove" in remaining
    assert "[mcp_servers.prod]" in remaining


def test_comments_annotating_our_own_keys_go_with_the_table() -> None:
    """Only the *trailing* run is ambiguous. Comments inside the table are ours."""
    text = (
        "[mcp_servers.repowise]\n# generated by repowise\n"
        'command = "repowise"\n[mcp_servers.prod]\nc = 1\n'
    )
    remaining = remove_table(text, "mcp_servers.repowise")

    assert "generated by repowise" not in remaining
    assert "[mcp_servers.prod]" in remaining


def test_a_file_holding_only_our_table_really_does_empty() -> None:
    assert remove_table('[mcp_servers.repowise]\ncommand = "repowise"\n', "mcp_servers.repowise") == ""


def test_a_sibling_with_our_name_as_a_prefix_is_untouched() -> None:
    text = '[mcp_servers.repowiseX]\ncommand = "x"\n'
    assert remove_table(text, "mcp_servers.repowise") == text


def test_crlf_endings_are_not_mixed_on_the_last_line() -> None:
    text = '[mcp_servers.repowise]\r\nc = 1\r\n[mcp_servers.b]\r\nc = 2\r\n'
    remaining = remove_table(text, "mcp_servers.repowise")

    assert "\n" not in remaining.replace("\r\n", "")


