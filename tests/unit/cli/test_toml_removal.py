def test_uninstall_does_not_delete_a_config_holding_the_users_comments(tmp_path: Path) -> None:
    """The end-to-end form of the critical bug."""
    repo = tmp_path / "repo"
    repo.mkdir()
    path = _write(
        repo,
        '[mcp_servers.repowise]\ncommand = "repowise"\n\n'
        '# [mcp_servers.other]\n# command = "other-server"\n',
    )

    write = remove_server_config(repo, drop_hooks_feature=False)

    assert write.action is FileAction.REMOVED
    assert path.exists(), "the file held the user's commented-out server and was deleted"
    body = path.read_text(encoding="utf-8")
    assert "other-server" in body
    assert "mcp_servers.repowise" not in body


def test_uninstall_still_deletes_a_config_that_was_only_ours(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
