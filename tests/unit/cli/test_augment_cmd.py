def _session_start(runner: CliRunner, cwd: Path, monkeypatch: pytest.MonkeyPatch):
    # The dedup marker is keyed on (event, context); identical blocks across
    # fast test runs would suppress the emission, so bypass it here.
    monkeypatch.setattr(
        "repowise.cli.commands.augment_cmd.command._claim_emission", lambda e, c: True
    )
    return _invoke_augment(
        runner,
        {
            "hook_event_name": "SessionStart",
            "source": "startup",
            "cwd": str(cwd),
        },
    )


def test_claude_session_start_gives_a_plugin_only_install_the_call_first_line(
    runner: CliRunner, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    from repowise.core.agent_steer import AGENT_STEER_DEFERRED as AGENT_STEER

    _init_repowise_repo(tmp_path)

    result = _session_start(runner, tmp_path, monkeypatch)

    assert result.exit_code == 0
    # tmp_path is not a git repo: no freshness fact, never a false "current"
    # claim; with no generated CLAUDE.md block the call-first line is new.
    context = _hook_context(result.output)
    assert AGENT_STEER in context
    assert "current" not in context


