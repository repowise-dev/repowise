"""The system map draws the code a repository ships, by each file's code origin."""

from __future__ import annotations

from types import SimpleNamespace

import networkx as nx

from repowise.core.generation.page_generator.system_map import build_run_system_map


def _run(files: dict[str, str], edges: list[tuple[str, str]], entry_points: list[str]):
    graph = nx.DiGraph()
    graph.add_edges_from((s, t, {"edge_type": "imports"}) for s, t in edges)
    parsed = [
        SimpleNamespace(
            file_info=SimpleNamespace(path=path, language=language, is_test=False),
            symbols=[object()],
        )
        for path, language in [
            *((p, "python") for p in files),
            *((f"{d}/pyproject.toml", "toml") for d in ("cli", "core", "api")),
        ]
    ]
    return SimpleNamespace(
        parsed_files=parsed,
        graph_builder=SimpleNamespace(graph=lambda: graph),
        external_systems=[],
        repo_path=None,
        repo_name="demo",
        pagerank={},
        kg_ctx=SimpleNamespace(get_entry_points=lambda: entry_points),
        source_map={p: text.encode() for p, text in files.items()},
        sel_module_groups=[],
    )


def _paths(files, edges, entry_points) -> set[str]:
    sm = build_run_system_map(_run(files, edges, entry_points))
    return {n.path for n in sm.nodes if n.path}


_SHIPPED = {
    "cli/tool/main.py": "",
    "core/engine.py": "",
    "core/store.py": "",
    "api/app.py": "",
}
_SHIPPED_EDGES = [
    ("cli/tool/main.py", "core/engine.py"),
    ("api/app.py", "core/engine.py"),
]


def test_tooling_and_generated_files_are_not_boxes():
    """A release script and a generated client are not parts of the system."""
    files = {
        **_SHIPPED,
        "scripts/release/main.py": "",
        "scripts/release/notes.py": "",
        "client/api_pb2.py": "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
        "client/models_pb2.py": "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n",
    }
    edges = [
        *_SHIPPED_EDGES,
        ("scripts/release/main.py", "core/engine.py"),
        ("client/api_pb2.py", "core/store.py"),
    ]
    paths = _paths(files, edges, ["cli/tool/main.py", "scripts/release/main.py"])
    assert not any(p.startswith(("scripts", "client")) for p in paths)
    assert {"cli", "core"} <= paths


def test_a_repository_of_shipped_code_draws_every_part():
    paths = _paths(dict(_SHIPPED), _SHIPPED_EDGES, ["cli/tool/main.py"])
    assert {"cli", "core", "api"} <= paths
