"""search_codebase lists a name's definitions in files the index skips.

The indexer never parses a generated file (a ``Code generated ... DO NOT
EDIT.`` banner or a generated suffix), so a type such a file declares has no
graph node. A search for a name that also has an indexed symbol must still
list those definitions, or its ``complete: true`` claims every match while
leaving the real declaration out.
"""

from __future__ import annotations

import subprocess
from datetime import UTC, datetime

import pytest

from repowise.core.persistence.models import GraphNode, WikiSymbol
from repowise.server.mcp_server import _edit_sites, _meta
from repowise.server.mcp_server.tool_search import search_codebase

_NOW = datetime(2026, 3, 19, 12, 0, 0, tzinfo=UTC)

_INDEXED = {
    "internal/sink.go": (
        "package analytics\n"
        "\n"
        "type EvaluationResponse struct {\n"
        "\tFlag string\n"
        "}\n"
        "\n"
        "func record(r EvaluationResponse) {}\n"
    ),
    "cmd/evaluate.go": "package cmd\n\nfunc variantEvaluationResponse() {}\n",
}
_GENERATED = {
    "rpc/flipt.pb.go": (
        "// Code generated by protoc-gen-go. DO NOT EDIT.\n"
        "\n"
        "package flipt\n"
        "\n"
        "type EvaluationResponse struct {\n"
        "\tFlag string\n"
        "}\n"
        "\n"
        "type VariantEvaluationResponse struct {\n"
        "\tKey string\n"
        "}\n"
        "\n"
        "func (x *EvaluationResponse) GetFlag() string { return x.Flag }\n"
    ),
    "docs/api.md": "The `EvaluationResponse` type:\n\n    type EvaluationResponse struct\n",
}
_SYMBOLS = [
    ("internal/sink.go", "EvaluationResponse", "struct", 3, 5),
    ("cmd/evaluate.go", "variantEvaluationResponse", "function", 3, 3),
]


@pytest.fixture
async def tree(setup_mcp, session, tmp_path, monkeypatch):
    for module in (_edit_sites, _meta):
        monkeypatch.setattr(module, "_working_tree_dirty_paths", lambda _p: frozenset())
    for rel, text in {**_INDEXED, **_GENERATED}.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(text, encoding="utf-8")
    git = ["git", "-C", str(tmp_path), "-c", "user.name=t", "-c", "user.email=t@t"]
    subprocess.run([*git, "init", "-q"], check=True)
    subprocess.run([*git, "add", "internal", "cmd", "rpc", "docs"], check=True)
    subprocess.run([*git, "commit", "-q", "-m", "seed"], check=True)
    rid = setup_mcp
    for i, rel in enumerate(_INDEXED):
        session.add(
            GraphNode(
                id=f"ud_file_{i}",
                repository_id=rid,
                node_id=rel,
                node_type="file",
                language="go",
                created_at=_NOW,
            )
        )
    for i, (rel, name, kind, start, end) in enumerate(_SYMBOLS):
        sid = f"{rel}::{name}"
        session.add(
            GraphNode(
                id=f"ud_sym_{i}",
                repository_id=rid,
                node_id=sid,
                node_type="symbol",
                name=name,
                file_path=rel,
                kind=kind,
                language="go",
                start_line=start,
                end_line=end,
                created_at=_NOW,
            )
        )
        session.add(
            WikiSymbol(
                id=f"ud_ws_{i}",
                repository_id=rid,
                file_path=rel,
                symbol_id=sid,
                name=name,
                qualified_name=name,
                kind=kind,
                signature=_INDEXED[rel].splitlines()[start - 1],
                start_line=start,
                end_line=end,
                language="go",
            )
        )
    await session.commit()
    return tmp_path


def _rows(out):
    return [(r["path"], r["line"], r["kind"]) for r in out.get("lines") or []]


@pytest.mark.asyncio
@pytest.mark.parametrize(
    "query", ["type EvaluationResponse struct", "EvaluationResponse", "struct EvaluationResponse"]
)
async def test_a_generated_definition_of_an_indexed_name_is_listed(tree, query):
    out = await search_codebase(query)

    rows = _rows(out)
    definitions = [r for r in rows if r[2] == "definition"]
    # The indexed symbol's definition leads; the generated one follows it.
    assert definitions[0] == ("internal/sink.go", 3, "definition"), rows
    assert ("rpc/flipt.pb.go", 5, "definition") in definitions, rows
    # A doc line spelling the declaration is no definition.
    assert not any(r[0] == "docs/api.md" for r in definitions), rows
    assert out["complete"] is True


@pytest.mark.asyncio
async def test_a_path_and_name_query_lists_the_generated_definition(tree):
    out = await search_codebase("rpc/flipt.pb.go EvaluationResponse")

    assert ("rpc/flipt.pb.go", 5, "definition") in _rows(out), out


@pytest.mark.asyncio
async def test_a_name_only_a_generated_file_spells_exactly_is_no_exact_match(tree):
    out = await search_codebase("VariantEvaluationResponse")

    assert _rows(out)[0] == ("rpc/flipt.pb.go", 9, "definition"), out
    # The indexed ``variantEvaluationResponse`` differs in case: not this name.
    assert out.get("exact_match") is not True, out


@pytest.mark.asyncio
async def test_an_indexed_name_no_unindexed_file_defines_is_unchanged(tree):
    out = await search_codebase("variantEvaluationResponse")

    assert _rows(out) == [("cmd/evaluate.go", 3, "definition")]
    assert out["complete"] is True
    assert out.get("exact_match") is True
